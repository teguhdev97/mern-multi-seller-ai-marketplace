CREATE TABLE IF NOT EXISTS seller (
  id VARCHAR(36) PRIMARY KEY,
  userId VARCHAR(36) NOT NULL UNIQUE,
  username VARCHAR(20) UNIQUE,
  name VARCHAR(255) NOT NULL,
  image TEXT,
  description TEXT,
  approved BOOLEAN NOT NULL DEFAULT FALSE,
  revokedAt DATETIME(3),
  revokedReason TEXT,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES `user` (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS product (
  id VARCHAR(36) PRIMARY KEY,
  sellerId VARCHAR(36) NOT NULL,
  name VARCHAR(255) NOT NULL,
  description TEXT,
  price DECIMAL(12,2) NOT NULL,
  discount DECIMAL(5,2) NOT NULL DEFAULT 0,
  category VARCHAR(50) NOT NULL,
  images JSON NOT NULL,
  stock INT UNSIGNED NOT NULL DEFAULT 0,
  sizes JSON NOT NULL,
  colors JSON NOT NULL,
  gender VARCHAR(30),
  status VARCHAR(30) NOT NULL DEFAULT 'draft',
  rejectionReason TEXT,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX product_catalog (status, category, createdAt),
  INDEX product_seller_status (sellerId, status),
  FOREIGN KEY (sellerId) REFERENCES seller (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS address (
  id VARCHAR(36) PRIMARY KEY,
  userId VARCHAR(36) NOT NULL,
  label VARCHAR(100) NOT NULL DEFAULT 'Home',
  street TEXT NOT NULL,
  city VARCHAR(150) NOT NULL,
  zip VARCHAR(30) NOT NULL,
  country VARCHAR(100) NOT NULL DEFAULT 'United States',
  isDefault BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES `user` (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS phone (
  id VARCHAR(36) PRIMARY KEY,
  userId VARCHAR(36) NOT NULL,
  number VARCHAR(50) NOT NULL,
  label VARCHAR(100) NOT NULL DEFAULT 'Mobile',
  isDefault BOOLEAN NOT NULL DEFAULT FALSE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (userId) REFERENCES `user` (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS promo (
  id VARCHAR(36) PRIMARY KEY,
  code VARCHAR(20) NOT NULL,
  discountPercent DECIMAL(5,2) NOT NULL,
  active BOOLEAN NOT NULL DEFAULT TRUE,
  sellerId VARCHAR(36),
  expiresAt DATETIME(3),
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY promo_seller_code (code, sellerId),
  FOREIGN KEY (sellerId) REFERENCES seller (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS `order` (
  id VARCHAR(36) PRIMARY KEY,
  userId VARCHAR(36) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'pending',
  deliveryStatus VARCHAR(30) NOT NULL,
  paymentMethod VARCHAR(30) NOT NULL,
  paymentStatus VARCHAR(30) NOT NULL DEFAULT 'pending',
  addressId VARCHAR(36),
  phoneId VARCHAR(36),
  addressSnapshot JSON,
  phoneNumber VARCHAR(50),
  promoCode VARCHAR(20),
  discount DECIMAL(12,2) NOT NULL DEFAULT 0,
  subtotal DECIMAL(12,2) NOT NULL,
  deliveryFee DECIMAL(12,2) NOT NULL DEFAULT 0,
  total DECIMAL(12,2) NOT NULL,
  stripeSessionId VARCHAR(255) UNIQUE,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  INDEX order_buyer_created (userId, createdAt),
  FOREIGN KEY (userId) REFERENCES `user` (id) ON DELETE CASCADE,
  FOREIGN KEY (addressId) REFERENCES address (id) ON DELETE SET NULL,
  FOREIGN KEY (phoneId) REFERENCES phone (id) ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS orderItem (
  id VARCHAR(36) PRIMARY KEY,
  orderId VARCHAR(36) NOT NULL,
  productId VARCHAR(36) NOT NULL,
  quantity INT UNSIGNED NOT NULL,
  price DECIMAL(12,2) NOT NULL,
  sellerId VARCHAR(36) NOT NULL,
  INDEX order_item_seller (sellerId, orderId),
  FOREIGN KEY (orderId) REFERENCES `order` (id) ON DELETE CASCADE,
  FOREIGN KEY (productId) REFERENCES product (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS review (
  id VARCHAR(36) PRIMARY KEY,
  productId VARCHAR(36) NOT NULL,
  userId VARCHAR(36) NOT NULL,
  rating TINYINT UNSIGNED NOT NULL,
  comment TEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY review_product_user (productId, userId),
  FOREIGN KEY (productId) REFERENCES product (id) ON DELETE CASCADE,
  FOREIGN KEY (userId) REFERENCES `user` (id) ON DELETE CASCADE,
  CHECK (rating BETWEEN 1 AND 5)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS reviewComment (
  id VARCHAR(36) PRIMARY KEY,
  reviewId VARCHAR(36) NOT NULL,
  userId VARCHAR(36) NOT NULL,
  comment TEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (reviewId) REFERENCES review (id) ON DELETE CASCADE,
  FOREIGN KEY (userId) REFERENCES `user` (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS aiInsight (
  id VARCHAR(36) PRIMARY KEY,
  sellerId VARCHAR(36) NOT NULL,
  type VARCHAR(30) NOT NULL,
  content LONGTEXT NOT NULL,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX insight_seller_created (sellerId, createdAt),
  FOREIGN KEY (sellerId) REFERENCES seller (id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS aiInsightStream (
  id VARCHAR(36) PRIMARY KEY,
  sellerId VARCHAR(36) NOT NULL,
  type VARCHAR(30) NOT NULL,
  status VARCHAR(30) NOT NULL DEFAULT 'processing',
  chunks JSON NOT NULL,
  error TEXT,
  createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updatedAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  FOREIGN KEY (sellerId) REFERENCES seller (id) ON DELETE CASCADE
) ENGINE=InnoDB;
